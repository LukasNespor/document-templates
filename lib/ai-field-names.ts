import AzureOpenAI from "openai";

// Hard cap on how much document context may ever leave the application
const MAX_CONTEXT_CHARS = 4000;

const PROMPT = `Jsi pomocník pro aplikaci na generování právních dokumentů.

Níže je seznam polí (placeholderů), která šablona obsahuje, a krátké úryvky textu z okolí těchto polí v dokumentu. Tvým úkolem je pro každé pole ze seznamu vygenerovat krátký, lidsky čitelný popis v češtině v 1. pádě (nominativ). Popis se použije jako placeholder v textovém poli formuláře.

## Pravidla

- Popis piš v 1. pádě (nominativ), např. "spisová značka", "počet dluhopisů", "identifikační číslo"
- Popis musí být stručný (max 5 slov)
- Vycházej výhradně z dodaných úryvků, nevymýšlej význam
- Úryvky jsou jen výseky dokumentu, nenavazují na sebe a nejsou úplné
- Pokud se pole vyskytuje ve více úryvcích, zohledni všechny výskyty
- Pokud z úryvků nelze význam jednoznačně určit, použij název pole tak jak je
- Vrať popis pro každé pole ze seznamu – žádné nepřidávej, žádné nevynechej

## Seznam polí

{FIELDS_LIST}

## Kontext polí

{FIELD_CONTEXTS}

## Výstup

Vrať JSON objekt, kde klíč je přesný název pole ze seznamu a hodnota je popis v 1. pádě. Vrať pouze JSON, nic jiného.`;

/**
 * Whether field display names may be generated by Azure OpenAI.
 * Disabled by default - enabling it sends placeholder context to an external service.
 */
export function isAiFieldNamesEnabled(): boolean {
  return process.env.AI_FIELD_NAMES_ENABLED === "true";
}

function getClient(): AzureOpenAI | null {
  const endpoint = process.env.AZURE_OPENAI_ENDPOINT;
  const apiKey = process.env.AZURE_OPENAI_API_KEY;

  if (!endpoint || !apiKey) {
    return null;
  }

  return new AzureOpenAI({
    apiKey,
    baseURL: `${endpoint}/openai/deployments/${process.env.AZURE_OPENAI_DEPLOYMENT || "gpt-4.1-mini"}`,
    defaultQuery: { "api-version": process.env.AZURE_OPENAI_API_VERSION || "2025-01-01-preview" },
    defaultHeaders: { "api-key": apiKey },
  });
}

/**
 * Trim the snippets so their combined length never exceeds maxChars.
 * The last snippet that does not fit is cut short, the rest is dropped.
 */
function limitContextSnippets(snippets: string[], maxChars: number): string[] {
  const limited: string[] = [];
  let used = 0;

  for (const snippet of snippets) {
    const remaining = maxChars - used;
    if (remaining <= 0) {
      break;
    }

    const part = snippet.length > remaining ? snippet.slice(0, remaining) : snippet;
    limited.push(part);
    used += part.length;
  }

  return limited;
}

export async function generateFieldDisplayNames(
  fields: string[],
  contextSnippets: string[]
): Promise<Record<string, string> | null> {
  if (!isAiFieldNamesEnabled()) {
    return null;
  }

  const client = getClient();
  if (!client) {
    console.warn("Azure OpenAI not configured, skipping field display name generation");
    return null;
  }

  if (fields.length === 0) {
    return {};
  }

  const limitedSnippets = limitContextSnippets(contextSnippets, MAX_CONTEXT_CHARS);
  const formattedContexts = limitedSnippets
    .map((snippet, index) => `Úryvek ${index + 1}:\n${snippet}`)
    .join("\n\n");

  const prompt = PROMPT
    .replace("{FIELDS_LIST}", fields.join(", "))
    .replace("{FIELD_CONTEXTS}", formattedContexts || "(žádný kontext k dispozici)");

  try {
    const response = await client.chat.completions.create({
      model: process.env.AZURE_OPENAI_DEPLOYMENT || "gpt-4o-mini",
      messages: [{ role: "user", content: prompt }],
      response_format: { type: "json_object" },
    });

    const content = response.choices[0]?.message?.content;
    if (!content) {
      console.error("Empty response from Azure OpenAI");
      return null;
    }

    const parsed = JSON.parse(content) as Record<string, string>;

    // Validate that all fields are present and no extra fields were added
    const result: Record<string, string> = {};
    for (const field of fields) {
      if (parsed[field] && typeof parsed[field] === "string") {
        result[field] = parsed[field];
      } else {
        result[field] = field;
      }
    }

    return result;
  } catch (error) {
    console.error("Failed to generate field display names:", error);
    return null;
  }
}
